"""Describe a freshly built feature table in results/dataset/DATASET.md."""

from pathlib import Path

import pandas as pd

from src.data.conditions import CONDITIONS
from src.features import FEATURE_COLUMNS
from src.reporting.tables import markdown_table

# Features shown per condition: a quick check that each edit does what it
# should (e.g. timing deviation shrinks with quantization strength, structure
# features stay put under partial quantization and drop under jitter).
SUMMARY_FEATURES = {
    "mag_timing_abs_mean": ("1/16 dev. (ms)", 1000),
    "mag_timing_std": ("1/16 SD (ms)", 1000),
    "mag_velocity_std": ("Velocity SD", 1),
    "struct_timing_autocorr": ("Autocorr.", 1),
    "struct_timing_position_r2": ("Position R²", 1),
    "struct_timing_instrument_r2": ("Instrument R²", 1),
    "struct_chord_spread_ratio": ("Chord spread", 1),
}


def write_dataset_summary(
    table: pd.DataFrame,
    skipped: pd.DataFrame,
    n_files: int,
    empty_clips: int,
    output: Path,
) -> None:
    """Write DATASET.md and condition_means.csv to `output`."""
    output.mkdir(parents=True, exist_ok=True)
    human = table[table.condition == "human"]

    means = table.groupby("condition", sort=False)[list(FEATURE_COLUMNS)].mean()
    means = means.reindex([c.name for c in CONDITIONS if c.name in means.index])
    means.to_csv(output / "condition_means.csv")

    lines = [
        "# Dataset", "",
        "Generated by `env/bin/python -m src.build_dataset`.", "",
        f"- MIDI files found: {n_files:,}",
        f"- Files used: {human.source_file.nunique():,}",
        f"- Files skipped: {len(skipped):,}",
    ]
    for reason, count in skipped.reason.value_counts().sort_index().items():
        lines.append(f"  - {reason}: {count:,}")
    lines += [
        f"- Two-bar clips: {human.source_clip_id.nunique():,} (empty clips skipped: {empty_clips})",
        f"- Drummers: {human.drummer.nunique()}",
        f"- Conditions: {table.condition.nunique()}, rows: {len(table):,}", "",
        "## Clips per drummer", "",
    ]
    per_drummer = human.groupby("drummer").agg(
        clips=("source_clip_id", "size"), performances=("source_file", "nunique"),
    )
    per_drummer = per_drummer.sort_index(key=lambda s: s.str.extract(r"(\d+)")[0].astype(float))
    lines += markdown_table(
        ["Drummer", "Clips", "Performances"],
        [[d, f"{r.clips:,}", r.performances] for d, r in per_drummer.iterrows()],
    )

    lines += ["", "## Mean feature values per condition", "",
              "Means over clips. Timing in milliseconds."]
    headers = ["Condition", *(label for label, _ in SUMMARY_FEATURES.values())]
    body = []
    for condition in CONDITIONS:
        if condition.name not in means.index:
            continue
        row = means.loc[condition.name]
        body.append([condition.label, *(f"{row[f] * scale:.3f}" for f, (_, scale) in SUMMARY_FEATURES.items())])
    lines += ["", *markdown_table(headers, body)]

    missing = human[list(FEATURE_COLUMNS)].isna().mean()
    missing = missing[missing > 0]
    lines += ["", "## Undefined feature values (human clips)", ""]
    if missing.empty:
        lines.append("None.")
    else:
        lines += markdown_table(
            ["Feature", "Share of clips"], [[f"`{f}`", f"{v:.1%}"] for f, v in missing.items()],
        )
    (output / "DATASET.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
