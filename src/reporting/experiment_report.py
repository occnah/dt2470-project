"""Write results/experiments/RESULTS.md from an experiment summary."""

from pathlib import Path

import pandas as pd

from src.common.config import RELIABLE_F1
from src.data.conditions import CONDITIONS, JITTER_KINDS
from src.reporting.tables import markdown_table, mean_sd

FAMILY_TITLES = {
    "quantize": "RQ1: quantization (timing)",
    "velocity": "RQ1: velocity normalization",
    "humanize": "RQ2: humanization after full 1/16 quantization",
    "shuffle": "RQ3 control: shuffled human deviations",
}

SERIES_LABELS = {
    "quantize_16": "1/16 quantization strength",
    "velocity": "Velocity normalization strength",
    **{f"humanize_{kind}": f"{kind.capitalize()} jitter SD" for kind in JITTER_KINDS},
}


def _family_table(summary: pd.DataFrame, family: str, models: list[tuple[str, str]]) -> list[str]:
    names = [c for c in CONDITIONS if c.family == family]
    headers = ["Condition", *(label for _, label in models)]
    rows = []
    for condition in names:
        cells = [condition.label]
        for model, _ in models:
            row = summary[(summary.condition == condition.name) & (summary.model == model)].iloc[0]
            mark = " ✓" if row.reliable else ""
            cells.append(f"{mean_sd(row.drummer_mean_f1, row.drummer_sd_f1)} (min {row.drummer_min_f1:.2f}){mark}")
        rows.append(cells)
    return markdown_table(headers, rows)


def write_experiment_report(
    summary: pd.DataFrame,
    thresholds: pd.DataFrame,
    config: dict,
    models: list[tuple[str, str]],
    output: Path,
) -> None:
    model_labels = dict(models)
    lines = [
        "# Experiment results", "",
        f"Generated by `env/bin/python -m src.run_experiments` on {config['run_at']}.", "",
        "## Protocol", "",
        f"- {config['n_source_clips']:,} two-bar clips from {config['n_drummers']} drummers; "
        f"{len(config['conditions'])} edited conditions, each its own balanced task "
        "(human version = class 0, edited version of the same clips = class 1).",
        "- Leave-one-drummer-out: every model is trained on all drummers but one and tested on "
        "the held-out drummer, for each drummer. All versions of a clip stay with their drummer.",
        "- Fixed model settings (no hyperparameter search); missing-value filling and scaling are "
        "fitted on the training fold only. Inputs are the context and feature columns listed in "
        "`run_config.json`; IDs, drummer, style and condition settings never enter a model.",
        f"- **Reliable** (✓) means F1 ≥ {RELIABLE_F1} for every held-out drummer. This criterion "
        "was fixed before this run.", "",
        "Cells: F1 for the edited class, mean ± SD over held-out drummers (each drummer weighted "
        "equally), and the lowest single-drummer F1. Pooled metrics and confusion counts are in "
        "`metrics.csv`; per-drummer results in `fold_metrics.csv`.", "",
    ]
    for family, title in FAMILY_TITLES.items():
        lines += [f"## {title}", "", *_family_table(summary, family, models), ""]
        if family == "quantize":
            lines += ["![Quantization curves](quantization_curves.png)", ""]
        if family == "humanize":
            lines += ["![Humanization curves](humanization_curves.png)", ""]

    lines += [
        "## Where detection becomes reliable", "",
        "Quantization and velocity: the lowest strength from which every stronger level is "
        "reliable. Humanization: the largest jitter SD up to which every smaller one is reliable. "
        "A dash means no level qualifies.", "",
    ]
    body = []
    for row in thresholds.itertuples():
        if pd.isna(row.level):
            level = "–"
        elif row.series.startswith("humanize"):
            level = f"{row.level:g} ms"
        else:
            level = f"{row.level:.0%}"
        body.append([model_labels.get(row.model, row.model), SERIES_LABELS.get(row.series, row.series), row.rule, level])
    lines += markdown_table(["Model", "Series", "Rule", "Level"], body)

    lines += [
        "", "## Per drummer", "", "![F1 per held-out drummer](f1_by_drummer.png)", "",
        "## Notes for interpretation", "",
        "- Full 1/16 quantization (all deviations exactly 0) and full velocity normalization "
        "(velocity SD exactly 0) are detectable by construction; they are sanity checks.",
        "- The timing rule sees only mean absolute timing deviation, so on the velocity conditions "
        "it is at chance by design (accuracy 0.5, F1 near 0); on the shuffled control the deviation "
        "sizes are identical, so it is at chance there too.",
        "- Structure features are scale-free, so partial quantization and partial velocity "
        "normalization leave them unchanged: only magnitude features can detect those.",
        "- At the matched level, jitter has each clip's human timing mean and SD, but the mean "
        "absolute deviation still differs slightly with the jitter's distribution shape. The "
        "shuffled control has exactly the human deviation sizes.",
        "- 1/f (pink) jitter is scaled over the whole performance, so within a two-bar clip its "
        "SD is smaller than the nominal level (slow drifts lie partly between clips).",
        "- Scores describe detection of these synthetic edits in this GMD subset, not what "
        "listeners hear.", "",
        "## Reproduce", "", "```bash", "env/bin/python -m src.build_dataset",
        "env/bin/python -m src.run_experiments", "```", "",
        f"Input table SHA-256: `{config['input_sha256']}`.", "",
    ]
    (output / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
