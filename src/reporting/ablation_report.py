"""Write results/ablation/ABLATION.md from an ablation summary."""

from pathlib import Path

import pandas as pd

from src.data.conditions import Condition
from src.features import FEATURE_GROUPS, MODEL_INPUTS
from src.models.classifiers import ModelSpec
from src.reporting.figures import plot_ablation
from src.reporting.tables import markdown_table

HEADLINE_SETS = ["all", "magnitude only", "structure only"]
# Conditions shown in the coefficient table: hard quantization cases and the
# cases where magnitude is matched to the human clip.
COEFFICIENT_CONDITIONS = (
    "quantize_16_25", "quantize_16_50", "velocity_25",
    "humanize_uniform_matched", "humanize_gaussian_matched", "humanize_pink_matched",
    "deviations_shuffled",
)


def _f1(summary: pd.DataFrame, model: str, feature_set: str, condition: str) -> float:
    row = summary[(summary.model == model) & (summary.feature_set == feature_set) & (summary.condition == condition)]
    return float(row.drummer_mean_f1.iloc[0])


def write_ablation_report(
    summary: pd.DataFrame,
    coefficients: pd.DataFrame,
    feature_sets: list[str],
    conditions: tuple[Condition, ...],
    models: tuple[ModelSpec, ...],
    output: Path,
) -> None:
    names = [c.name for c in conditions]
    lines = [
        "# Feature ablation (RQ3)", "",
        "Generated by `env/bin/python -m src.run_ablation`. Same leave-one-drummer-out protocol "
        "as `results/experiments/`, with different feature sets. Cells are F1 for edited clips, "
        "mean over held-out drummers. Context features (tempo, note count) are in every set.", "",
        "A feature set that cannot separate the classes at all makes a model predict one class "
        "for everything: F1 is then 0 (or about 0.67), while accuracy is 0.5. Structure features "
        "are unchanged by partial quantization, so \"structure only\" is at that floor there by "
        "construction. Accuracy is in `ablation_metrics.csv`.", "",
        "At full 1/16 quantization and full velocity normalization, \"structure only\" still scores "
        "high: a clip without timing (or velocity) spread gets structure values of 0 by convention, "
        "which itself reveals the edit. That is a sanity check, not evidence of structure.", "",
        "Per-instrument timing and IOI features are listed as magnitude, but they also depend on "
        "which notes have which deviation. This is why \"magnitude only\" is above chance on the "
        "shuffled control, whose overall deviation sizes are identical to the human clip.", "",
        "Feature groups:", "",
    ]
    lines += [f"- `{group}`: {', '.join(f'`{c}`' for c in columns)}" for group, columns in FEATURE_GROUPS.items()]

    for model in models:
        lines += ["", f"## {model.label}", "",
                  "### Magnitude versus structure", ""]
        body = []
        for condition in conditions:
            values = [_f1(summary, model.name, s, condition.name) for s in HEADLINE_SETS]
            body.append([condition.label, *(f"{v:.3f}" for v in values)])
        lines += markdown_table(["Condition", *HEADLINE_SETS], body)

        figure = f"ablation_{model.name}.png"
        plot_ablation(summary, HEADLINE_SETS, names, model.name, output / figure)
        lines += ["", f"![Magnitude versus structure, {model.label}]({figure})", "",
                  "### Change in F1 when one group is removed", ""]
        dropped = [s for s in feature_sets if s.startswith("without ")]
        body = []
        for condition in conditions:
            full = _f1(summary, model.name, "all", condition.name)
            body.append([condition.label, *(f"{_f1(summary, model.name, s, condition.name) - full:+.3f}" for s in dropped)])
        lines += markdown_table(["Condition", *(s.removeprefix("without ") for s in dropped)], body)

    if not coefficients.empty:
        lines += ["", "## Logistic-regression coefficients (all features)", "",
                  "Mean standardized coefficient over held-out-drummer folds. Positive values push "
                  "toward \"edited\". Coefficients of correlated features share weight, so read "
                  "them together with the ablation above.", ""]
        mean = coefficients.groupby(["feature", "condition"]).coefficient.mean().unstack()
        mean = mean.reindex(columns=[n for n in COEFFICIENT_CONDITIONS if n in mean.columns])
        mean = mean.reindex([f for f in MODEL_INPUTS if f in mean.index])
        lines += markdown_table(
            ["Feature", *mean.columns],
            [[f"`{feature}`", *(f"{v:+.2f}" for v in row)] for feature, row in mean.iterrows()],
        )

    lines += ["", "## Reproduce", "", "```bash", "env/bin/python -m src.run_ablation", "```", ""]
    (output / "ABLATION.md").write_text("\n".join(lines), encoding="utf-8")
